#!/usr/bin/env python3
"""Writes app/fonts.css: Inter (SIL OFL, rsms.me/inter) cut down to the characters the app uses, as WOFF in base64, so the app looks the same on every device
and the headings use the same letter shapes as the logo. Run by hand when the character set or weights change; the result is committed.
Needs fonttools (pip install fonttools) and the Inter OTF files (Debian: fonts-inter, /usr/share/fonts/opentype/inter)."""
import base64,io,os,sys
from fontTools import subset
from fontTools.ttLib import TTFont
SRC="/usr/share/fonts/opentype/inter/Inter-%s.otf"
WEIGHTS=[("Regular",400),("SemiBold",600),("Bold",700),("Black",900)]
# Basic Latin, Latin-1 (æøå, é, ü ...), Latin Extended-A (ł, š, č ...), typographic punctuation, arrows, check marks
UNI="U+0020-007E,U+00A0-017F,U+2010-2015,U+2018-201E,U+2022,U+2026,U+2032-2033,U+20AC,U+2190-2193,U+2713,U+2715,U+00B7,U+2212"
out=["/* Generated by app/make-fonts.py - do not edit by hand. Inter (SIL OFL 1.1, Rasmus Andersson). */"]
for name,w in WEIGHTS:
    opts=subset.Options();opts.flavor="woff";opts.layout_features=["kern","ccmp","locl","mark","mkmk"];opts.name_IDs=[1,2];opts.notdef_outline=True;opts.hinting=False
    f=TTFont(SRC%name);s=subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(UNI));s.subset(f)
    b=io.BytesIO();f.flavor="woff";f.save(b);d=b.getvalue()
    print(name,len(d),file=sys.stderr)
    out.append('@font-face{font-family:"Inter";font-style:normal;font-weight:%d;font-display:swap;src:url(data:font/woff;base64,%s) format("woff")}'%(w,base64.b64encode(d).decode()))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)),"fonts.css"),"w").write("\n".join(out)+"\n")
